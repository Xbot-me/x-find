const names = new Intl.DisplayNames(['en'], { type: 'region' });

/** "usa" → "United States"; unknown codes come back upper-cased ("ZZZ"). */
export function countryName(alpha3: string): string {
  if (alpha3.toLowerCase() === 'zzz') return 'Unknown'; // Search Console's code for an unknown country
  const a2 = ALPHA3_TO_ALPHA2[alpha3.toLowerCase()];
  if (!a2) return alpha3.toUpperCase();
  try {
    return names.of(a2) ?? alpha3.toUpperCase();
  } catch {
    return alpha3.toUpperCase();
  }
}
